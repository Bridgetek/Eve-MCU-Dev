// Store bitmap data in RAM_G and setup bitmap handle
static int32_t spaced_invaders_StoreBitmaps(uint32_t scale, uint8_t handle, int32_t storeat, bitmap_info_t * bitmap_info,
                                       const uint8_t * bitmap_data)
{
    uint32_t offset = 0;
    uint32_t start = storeat;
    uint8_t ramData[512];
    const uint8_t *pm_addr = bitmap_data;
    uint32_t left;
    // calculate storage requirements for bitmap ...
    uint32_t bitmap_datasize = bitmap_info->Height * bitmap_info->Stride;

    while (offset < bitmap_datasize)
    {
        memcpy(ramData, pm_addr, 512);

        if (bitmap_datasize - offset < 512)
        {
            left = bitmap_datasize - offset;
        }
        else
        {
            left = 512;
        }
        EVE_LIB_WriteDataToRAMG(ramData, left, storeat);
        offset += left;
        pm_addr += left;
        storeat += left;
    };

    // start of new display list ...
    EVE_LIB_BeginCoProList();
    EVE_CMD_DLSTART();
    EVE_BEGIN(EVE_BEGIN_BITMAPS);
    EVE_BITMAP_HANDLE(handle);
    EVE_BITMAP_SOURCE(start);
    EVE_BITMAP_LAYOUT(bitmap_info->Format, bitmap_info->Stride, bitmap_info->Height / bitmap_info->Cells);
#if IS_EVE_API(2, 3, 4, 5)
    EVE_BITMAP_LAYOUT_H(bitmap_info->Stride >> 10, (bitmap_info->Height / bitmap_info->Cells) >> 9);
#endif
    EVE_BITMAP_SIZE(EVE_FILTER_NEAREST, EVE_WRAP_BORDER, EVE_WRAP_BORDER, SCALE(bitmap_info->Width, scale), SCALE(bitmap_info->Height, scale));
#if IS_EVE_API(2, 3, 4, 5)
    EVE_BITMAP_SIZE_H(SCALE(bitmap_info->Width, scale) >> 9, SCALE(bitmap_info->Height, scale) >> 9);
#endif
    EVE_END();
    // end of display list ...
    EVE_DISPLAY();
    // Swap between frames
    EVE_CMD_SWAP();
    // Download the commands into fifo
    EVE_LIB_EndCoProList();
    // Wait till coprocessor completes the operation
    EVE_LIB_AwaitCoProEmpty();

    // return address to store following data at...
    return (storeat);
}

// Load all bitmaps in RAM_G and setup the bitmap handles
void spaced_invaders_LoadBitmaps(uint32_t scale)
{
    ramInvader = 0;
    ramShields = spaced_invaders_StoreBitmaps(scale, BITMAP_INVADERS, ramInvader, &InvaderImageInfo, InvaderImageData);
    ramNextBit = spaced_invaders_StoreBitmaps(scale, BITMAP_SHIELDS, ramShields, &ShieldsImageInfo, ShieldsImageData);
}